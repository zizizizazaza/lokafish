// Map a Zep entity-type label → a Lokafish category bucket
function categoryForEntity(labels) {
  const lset = new Set((labels || []).map(l => l.toLowerCase()))
  if (lset.has('person')) return { id: 'people', label: 'People', color: COLORS.blue, icon: '👥' }
  if (lset.has('govagency') || lset.has('government') || lset.has('agency')) return { id: 'govt', label: 'Government', color: COLORS.red, icon: '🏛️' }
  if (lset.has('company') || lset.has('organization') || lset.has('business')) return { id: 'corp', label: 'Companies', color: COLORS.orange, icon: '🏢' }
  if (lset.has('mediaoutlet') || lset.has('media')) return { id: 'media', label: 'Media', color: COLORS.purple, icon: '📰' }
  if (lset.has('event')) return { id: 'events', label: 'Events', color: COLORS.pink, icon: '🎤' }
  if (lset.has('location') || lset.has('place')) return { id: 'places', label: 'Places', color: COLORS.green, icon: '📍' }
  return { id: 'concepts', label: 'Concepts', color: COLORS.orange, icon: '◆' }
}

function buildAgentCategories(entities, profiles) {
  // entities: from 02_entities.json (Zep filtered entities)
  // profiles: from 03d_profiles.json (OASIS-ready personas with bio/age/etc)

  const profileById = new Map()
  if (profiles) {
    const list = Array.isArray(profiles) ? profiles
                : profiles.profiles || profiles.data || []
    for (const p of list) {
      const id = p.user_id || p.id || p.uuid || p.name
      if (id) profileById.set(String(id), p)
    }
  }

  // Group entities by category
  const buckets = new Map()
  const entList = entities?.entities || entities?.nodes || []
  for (const ent of entList) {
    const cat = categoryForEntity(ent.labels || ent.label_list || [])
    if (!buckets.has(cat.id)) {
      buckets.set(cat.id, { ...cat, agents: [], count: 0, bgColor: hexToRgba(cat.color, 0.08) })
    }
    const bucket = buckets.get(cat.id)
    const profile = profileById.get(String(ent.uuid)) || profileById.get(ent.name) || {}
    const persona = profile.persona || profile.bio || ent.summary || ''
    bucket.agents.push({
      name: ent.name || profile.name || 'Unknown',
      role: profile.profession || profile.role || (ent.labels?.[0]) || 'Entity',
      avatar: `https://api.dicebear.com/7.x/notionists/svg?seed=${encodeURIComponent(ent.name || 'x')}`,
      influence: typeof profile.influence === 'number' ? profile.influence
                : Math.min(0.95, 0.4 + ((ent.name || '').length % 6) * 0.1),
      traits: (profile.interested_topics || profile.interests || []).slice(0, 2),
      age: profile.age || null,
      income: profile.income || 'N/A',
      personality: profile.personality || null,
      background: persona.slice(0, 280) || ent.summary || '',
      decisionLogic: profile.decision_logic || profile.persona || '',
      consumptionProfile: profile.consumption_profile || '',
      uuid: ent.uuid,
    })
    bucket.count = bucket.agents.length
  }

  return Array.from(buckets.values())
}

function hexToRgba(hex, alpha) {
  const h = hex.replace('#', '')
  const r = parseInt(h.substring(0, 2), 16)
  const g = parseInt(h.substring(2, 4), 16)
  const b = parseInt(h.substring(4, 6), 16)
  return `rgba(${r},${g},${b},${alpha})`
}

function buildBehaviorChain(actions) {
  // Build a 4-step chain summarizing the dominant verbs in actions
  const verbs = new Map()
  for (const a of (actions || []).slice(0, 200)) {
    const t = a.action_type || a.type || a.action || 'ACT'
    verbs.set(t, (verbs.get(t) || 0) + 1)
  }
  const top = Array.from(verbs.entries()).sort((a, b) => b[1] - a[1]).slice(0, 5)
  return top.map(([label, count], i) => ({
    label: label.replace(/_/g, ' '),
    value: `${count.toLocaleString()} actions`,
  }))
}

function buildKgLogMessages(meta, entCount, edgeCount) {
  return [
    `Loading scenario: ${meta.requirement?.slice(0, 60) || 'unknown'}...`,
    'Extracting entity types from document...',
    `Built ${entCount} entities and ${edgeCount} relations`,
    'Sampling personas from population database...',
    'Generating OASIS agent profiles via LLM...',
    'Compiling economic behavior chains...',
    'World construction complete',
  ]
}

