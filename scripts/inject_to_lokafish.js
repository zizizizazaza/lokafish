function buildSimulationPosts(actions, profiles) {
  // Take the first ~14 CREATE_POST or content-bearing actions, format as feed posts
  const profileById = new Map()
  if (profiles) {
    const list = Array.isArray(profiles) ? profiles : profiles.profiles || profiles.data || []
    for (const p of list) {
      const id = p.user_id || p.id || p.name
      if (id) profileById.set(String(id), p)
    }
  }

  const posts = []
  let seq = 0
  for (const a of actions || []) {
    if (posts.length >= 14) break
    const args = a.action_args || a.args || {}
    const text = args.content || args.text || a.content || ''
    if (!text || text.length < 30) continue
    const round = a.round_num || a.round || 0
    const agentName = a.agent_name || profileById.get(String(a.agent_id))?.name || `Agent ${a.agent_id}`
    const handle = (agentName || 'agent').toLowerCase().replace(/\s+/g, '_')
    posts.push({
      avatar: `https://api.dicebear.com/7.x/notionists/svg?seed=${encodeURIComponent(agentName)}`,
      handle: agentName,
      username: `@${handle}`,
      time: `Round ${round}`,
      text: text.slice(0, 380),
      likes: 100 + ((seq * 173) % 9000),
      reposts: 20 + ((seq * 91) % 4000),
      sentiment: detectSentiment(text),
    })
    seq++
  }
  return posts
}

function detectSentiment(text) {
  const t = text.toLowerCase()
  const pos = ['great', 'amazing', 'love', 'wonderful', 'best', 'fantastic', 'excited']
  const neg = ['bad', 'terrible', 'worst', 'hate', 'awful', 'disappointing']
  if (pos.some(w => t.includes(w))) return 'positive'
  if (neg.some(w => t.includes(w))) return 'negative'
  return 'neutral'
}

function buildChatResponses(reportContent) {
  // Take headings and excerpts from the markdown report → chat panel suggestions
  const md = reportContent || ''
  const responses = {}
  // Look for ## sections
  const sections = md.split(/^## /gm).slice(1)
  const labels = ['Summarize the key findings', 'What are the main risks?', 'Explain the methodology', 'How does this compare to actuals?']
  for (let i = 0; i < Math.min(sections.length, labels.length); i++) {
    const heading = sections[i].split('\n')[0].trim()
    const body = sections[i].split('\n').slice(1).join('\n').trim().slice(0, 800)
    responses[labels[i]] = `**${heading}**\n\n${body}`
  }
  // Always include at least one fallback
  if (Object.keys(responses).length === 0) {
    responses['Summarize the key findings'] = 'Simulation complete. Detailed report available in Stage 5.'
  }
  return responses
}

function buildMetricsTimeline(actions) {
  // Aggregate actions per round into 4 metric series
  const byRound = new Map()
  for (const a of actions || []) {
    const r = a.round_num || a.round || 0
    if (!r) continue
    byRound.set(r, (byRound.get(r) || 0) + 1)
  }
  const rounds = Array.from(byRound.keys()).sort((a, b) => a - b)
  const tot = actions?.length || 1
  // Synthesize 4 metric trajectories
  return rounds.map((r) => {
    const count = byRound.get(r)
    const ratio = count / Math.max(...byRound.values())
    return {
      round: r,
      gdp_m: Math.round(80 + ratio * 320),   // S$M tourism receipts
      jobs: Math.round(2000 + ratio * 14000),
      occupancy: Math.round(75 + ratio * 18), // %
      changi_pax: Math.round(175 + ratio * 60), // K/wk
    }
  })
}

function generateSimulationJs(meta, actions, profiles, reportContent) {
  const banner = writeFileBanner(meta)
  const posts = buildSimulationPosts(actions, profiles)
  const chat = buildChatResponses(reportContent)
  const timeline = buildMetricsTimeline(actions)
  const baseline = { gdp_m: 80, jobs: 2000, occupancy: 75, changi_pax: 175 }

  return `${banner}
export const simulationPosts = ${jsLiteral(posts)};

export const chatResponses = ${jsLiteral(chat)};

export const metricsTimeline = ${jsLiteral(timeline)};

export const metricsBaseline = ${jsLiteral(baseline)};
`
}

