#!/usr/bin/env node
// Lokafish snapshot pipeline — Stage 3/3:
// Take the raw MiroFish snapshot + the Stage 4 chart aggregations and regenerate
// lokafish/src/data/*.js so the UI shows REAL data captured from a real MiroFish
// run. The lokafish screens themselves don't need to change — they just import
// from `data/*.js` as before, but those files are now compiled artifacts.
//
// Usage (from lokafish project root):
//   node scripts/inject_to_lokafish.js \
//        --raw    public/snapshots/raw \
//        --charts public/snapshots/charts \
//        --target src/data
//
// It rewrites:
//   src/data/agents.js     ← personas from real Zep entities + real MiroFish profiles
//   src/data/simulation.js ← top OASIS actions as feed posts + chat suggestions
//   src/data/analytics.js  ← aggregated chart data
//   src/data/report.js     ← real markdown report from ReportAgent
//
// Each file gets a header banner with the snapshot timestamp + sim id so you
// know it's a generated artifact, not hand-edited.

const fs = require('fs')
const path = require('path')

// ---------------------------------------------------------------------------
// Argv parsing
// ---------------------------------------------------------------------------
function parseArgs() {
  const args = process.argv.slice(2)
  const out = {
    raw: 'public/snapshots/raw',
    charts: 'public/snapshots/charts',
    target: 'src/data',
  }
  for (let i = 0; i < args.length; i++) {
    const a = args[i]
    if (a === '--raw' && args[i + 1]) { out.raw = args[++i]; continue }
    if (a === '--charts' && args[i + 1]) { out.charts = args[++i]; continue }
    if (a === '--target' && args[i + 1]) { out.target = args[++i]; continue }
    if (a === '--help' || a === '-h') {
      console.log("see top of inject_to_lokafish.js")
      process.exit(0)
    }
  }
  return out
}

// ---------------------------------------------------------------------------
// File helpers
// ---------------------------------------------------------------------------
function readJSON(p) {
  if (!fs.existsSync(p)) return null
  try { return JSON.parse(fs.readFileSync(p, 'utf-8')) }
  catch (e) { console.warn(`  WARN: could not parse ${p}: ${e.message}`); return null }
}

function readText(p) {
  if (!fs.existsSync(p)) return null
  return fs.readFileSync(p, 'utf-8')
}

function writeFileBanner(meta) {
  return `// AUTO-GENERATED by scripts/inject_to_lokafish.js
// Source snapshot: ${meta.simulation_id || 'unknown'}
// Captured at:    ${meta.captured_at || 'unknown'}
// DO NOT EDIT BY HAND — re-run the inject script after recapturing.
`
}

function jsLiteral(value, indent = 0) {
  // Pretty JSON with double-quoted strings (valid JS)
  return JSON.stringify(value, null, 2)
}

