function main() {
  const args = parseArgs()
  const rawDir = path.resolve(args.raw)
  const chartsDir = path.resolve(args.charts)
  const targetDir = path.resolve(args.target)

  console.log(`[inject] raw    : ${rawDir}`)
  console.log(`[inject] charts : ${chartsDir}`)
  console.log(`[inject] target : ${targetDir}`)

  if (!fs.existsSync(rawDir))    throw new Error(`raw dir not found: ${rawDir}`)
  if (!fs.existsSync(chartsDir)) throw new Error(`charts dir not found: ${chartsDir}`)
  if (!fs.existsSync(targetDir)) throw new Error(`target dir not found: ${targetDir}`)

  const meta      = readJSON(path.join(rawDir, '99_capture_meta.json')) || {}
  const ontology  = readJSON(path.join(rawDir, '00_ontology.json')) || {}
  const entities  = readJSON(path.join(rawDir, '02_entities.json')) || {}
  const graphData = readJSON(path.join(rawDir, '02b_graph_data.json'))
  const profiles  = readJSON(path.join(rawDir, '03d_profiles.json'))
  const actionsRaw= readJSON(path.join(rawDir, '04c_actions.json')) || {}
  const detail    = readJSON(path.join(rawDir, '04d_run_status_detail.json')) || {}
  const reportMd  = readText(path.join(rawDir, '05c_report.md')) || ''

  // Collect actions list (try multiple sources)
  let actions = []
  if (Array.isArray(actionsRaw)) actions = actionsRaw
  else if (actionsRaw.all_actions) actions = actionsRaw.all_actions
  else if (actionsRaw.actions) actions = actionsRaw.actions
  else if (actionsRaw.data?.all_actions) actions = actionsRaw.data.all_actions
  if (!actions.length && detail.all_actions) actions = detail.all_actions
  console.log(`[inject] loaded ${actions.length} actions`)

  // Load chart files
  const charts = {
    heatmap:   readJSON(path.join(chartsDir, 'heatmap.json')),
    gdp:       readJSON(path.join(chartsDir, 'gdp.json')),
    industry:  readJSON(path.join(chartsDir, 'industry.json')),
    flow:      readJSON(path.join(chartsDir, 'flow.json')),
    sentiment: readJSON(path.join(chartsDir, 'sentiment.json')),
  }

  // Generate the 4 data files
  const agentsJs     = generateAgentsJs(meta, entities, graphData, profiles, actions)
  const simulationJs = generateSimulationJs(meta, actions, profiles, reportMd)
  const analyticsJs  = generateAnalyticsJs(meta, charts)
  const reportJs     = generateReportJs(meta, reportMd, meta)

  fs.writeFileSync(path.join(targetDir, 'agents.js'),     agentsJs,     'utf-8')
  fs.writeFileSync(path.join(targetDir, 'simulation.js'), simulationJs, 'utf-8')
  fs.writeFileSync(path.join(targetDir, 'analytics.js'),  analyticsJs,  'utf-8')
  fs.writeFileSync(path.join(targetDir, 'report.js'),     reportJs,     'utf-8')

  console.log()
  console.log('[inject] DONE — wrote 4 files:')
  console.log('  src/data/agents.js')
  console.log('  src/data/simulation.js')
  console.log('  src/data/analytics.js')
  console.log('  src/data/report.js')
  console.log()
  console.log('[inject] next: cd lokafish && npm run dev')
  console.log('[inject] then visit http://localhost:5173')
}

main()
