function mdToHtmlSections(md) {
  // Parse the markdown report into Lokafish's reportContent shape
  if (!md) return []
  const sections = []
  const splits = md.split(/^## /gm).slice(1)
  for (let i = 0; i < splits.length; i++) {
    const block = splits[i]
    const heading = block.split('\n')[0].trim()
    const bodyMd = block.split('\n').slice(1).join('\n').trim()
    sections.push({
      num: String(i + 1),
      title: heading,
      body: mdBodyToHtml(bodyMd),
    })
  }
  return sections
}

function mdBodyToHtml(md) {
  // Very small markdown → HTML for paragraphs, bold, italic, lists, tables
  const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const inline = (s) => escape(s)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
  const lines = md.split('\n')
  let html = ''
  let inList = false
  let inTable = false
  let tableRows = []
  const flushList = () => { if (inList) { html += '</ul>'; inList = false } }
  const flushTable = () => {
    if (!inTable) return
    if (tableRows.length >= 2) {
      const head = tableRows[0]
      const body = tableRows.slice(2)
      html += '<div class="report-data-table"><table><thead><tr>'
      head.forEach(c => html += `<th>${inline(c.trim())}</th>`)
      html += '</tr></thead><tbody>'
      body.forEach(row => {
        html += '<tr>'
        row.forEach(c => html += `<td>${inline(c.trim())}</td>`)
        html += '</tr>'
      })
      html += '</tbody></table></div>'
    }
    inTable = false
    tableRows = []
  }
  for (const raw of lines) {
    const line = raw.replace(/\r$/, '')
    if (/^\|.*\|$/.test(line)) {
      if (!inTable) { flushList(); inTable = true; tableRows = [] }
      tableRows.push(line.slice(1, -1).split('|'))
      continue
    } else if (inTable) {
      flushTable()
    }
    if (line.startsWith('- ')) {
      if (!inList) { html += '<ul style="padding-left: 24px; margin: 10px 0;">'; inList = true }
      html += `<li>${inline(line.slice(2))}</li>`
      continue
    }
    if (line.trim() === '') { flushList(); continue }
    flushList()
    html += `<p>${inline(line)}</p>`
  }
  flushTable()
  flushList()
  return html
}

function generateReportJs(meta, reportContent, captureMeta) {
  const banner = writeFileBanner(meta)
  const sections = mdToHtmlSections(reportContent)
  const title = sections[0]?.title || 'Loka Simulation Report'
  // Strip section 1 if it's the title
  const data = {
    classification: 'CONFIDENTIAL',
    date: new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }),
    model: 'Multi-Agent Simulation × Quantitative Economic Analysis',
    title: title,
    subtitle: captureMeta.requirement?.slice(0, 140) || '',
    abstract: extractAbstract(reportContent) || '',
    sections: sections.length ? sections : [{ num: '1', title: 'Report', body: '<p>No report content captured.</p>' }],
    references: [
      `Captured from MiroFish backend on ${meta.captured_at || 'unknown'}`,
      `Simulation ID: ${meta.simulation_id || 'unknown'}`,
      `Project ID: ${meta.project_id || 'unknown'}`,
    ],
    risks: extractRisks(reportContent),
  }
  return `${banner}
export const reportContent = ${jsLiteral(data)};
`
}

function extractAbstract(md) {
  if (!md) return ''
  const m = md.match(/(?:^#\s.+\n)?([\s\S]*?)(?=\n## |$)/)
  return m ? m[1].trim().slice(0, 1200) : ''
}

function extractRisks(md) {
  if (!md) return []
  const m = md.match(/##\s*(?:Risks?|Limitations?|Discussion)[\s\S]*?(?=\n## |$)/i)
  if (!m) return ['No explicit risk section captured.']
  return m[0].split('\n').filter(l => l.trim().startsWith('- ')).map(l => l.replace(/^-\s*/, '').slice(0, 240)).slice(0, 6)
}

